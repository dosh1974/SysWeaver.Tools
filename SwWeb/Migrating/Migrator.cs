using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using SwWeb.Checking;
using SwWeb.Lexing;

namespace SwWeb.Migrating
{
    /// <summary>
    /// The result of a migrate run.
    /// </summary>
    public sealed class MigrateResult
    {
        /// <summary>
        /// All report items (changes, info, warnings), sorted by path and position.
        /// </summary>
        public readonly List<MigrateItem> Items = new List<MigrateItem>();
        /// <summary>
        /// Relative paths of the files that were changed (or would be, with --dry-run).
        /// </summary>
        public readonly List<String> ChangedFiles = new List<String>();
        /// <summary>
        /// Number of .js / .css / .html files analyzed.
        /// </summary>
        public int FilesScanned;
        /// <summary>
        /// Number of files skipped (vendored, generated, library folders, include / exclude).
        /// </summary>
        public int FilesSkipped;
        /// <summary>
        /// Number of HTML pages that include the legacy bundles.
        /// </summary>
        public int LegacyPages;
        /// <summary>
        /// Number of pages whose includes were rewritten.
        /// </summary>
        public int PagesMigrated;
        /// <summary>
        /// Number of legacy pages whose includes were kept (legacy globals remain).
        /// </summary>
        public int PagesBlocked;
        /// <summary>
        /// Number of migrated pages that got the compatibility bundle sw/compat.js (legacy globals remain).
        /// </summary>
        public int PagesCompat;
        /// <summary>
        /// Number of framework-free UI pages (no Sw or legacy bundle, rule no-framework).
        /// </summary>
        public int FrameworkFreePages;
        /// <summary>
        /// True if nothing was written (dry run).
        /// </summary>
        public bool DryRun;
        /// <summary>
        /// The run was an "upgrade" (the report title says so).
        /// </summary>
        public bool Upgrade;
        /// <summary>
        /// Number of changes.
        /// </summary>
        public int Changes => Items.Count(x => x.Kind == MigrateItemKind.Change);
        /// <summary>
        /// Number of warnings.
        /// </summary>
        public int Warnings => Items.Count(x => x.Kind == MigrateItemKind.Warning);
        /// <summary>
        /// Number of infos.
        /// </summary>
        public int Infos => Items.Count(x => x.Kind == MigrateItemKind.Info);
    }

    /// <summary>
    /// The "migrate" command: rewrites an old format front end folder to the new Sw format (include tags, legacy global renames, css hooks report).
    /// </summary>
    public static class Migrator
    {
        /// <summary>
        /// Paths that migrate never touches in addition to <see cref="CheckOptions.DefaultSkip"/>: the new library folders,
        /// the legacy compatibility bundles and the templated theme source.
        /// </summary>
        public static readonly IReadOnlyList<String> ExtraSkip = new[]
        {
            "core/", "ui/", "shell/", "sw/",
            "**/common/common.js", "**/app/application.js", "**/app/application.css", "**/common/theme.css", "**/common/common.css",
            "common/common.js", "app/application.js", "app/application.css", "common/theme.css", "common/common.css",
        };

        /// <summary>
        /// The marker of generated bundles (never migrated).
        /// </summary>
        public const String GeneratedMarker = "GENERATED by SwWeb";

        sealed class FileState
        {
            public String Rel;
            public String Full;
            public String Ext;
            public SourceText Src;
            public JsScope Scope;                       // .js files
            public List<JsScope> InlineScopes;          // .html inline scripts (pre-pass)
            public JsAnalysis Js;
            public readonly List<TextEdit> Edits = new List<TextEdit>();
            public readonly List<OffsetItem> Items = new List<OffsetItem>();
            public String NewText;                      // the text after the edits (set before the report / write)
            public List<TextEdit> Applied;              // the edits that were applied, in order (to map the new text back to the old lines)
        }

        /// <summary>
        /// Apply the edits of a file to its text (overlapping edits are skipped).
        /// </summary>
        static (String Text, List<TextEdit> Applied, List<TextEdit> Skipped) ApplyEdits(String text, List<TextEdit> list)
        {
            var edits = list.OrderBy(x => x.Start).ThenBy(x => x.End).ToList();
            var applied = new List<TextEdit>();
            var skipped = new List<TextEdit>();
            var sb = new StringBuilder(text.Length + 256);
            int pos = 0;
            foreach (var e in edits)
            {
                if (e.Start < pos)
                {
                    skipped.Add(e);
                    continue;
                }
                if ((e.End - e.Start == e.Text.Length) && (String.CompareOrdinal(text, e.Start, e.Text, 0, e.Text.Length) == 0))
                    continue;
                sb.Append(text, pos, e.Start - pos);
                sb.Append(e.Text);
                pos = e.End;
                applied.Add(e);
            }
            sb.Append(text, pos, text.Length - pos);
            return (sb.ToString(), applied, skipped);
        }

        /// <summary>
        /// Map an offset of the edited text back to the original text (an offset inside a replacement maps to its start).
        /// </summary>
        static int OldOffset(List<TextEdit> applied, int newOffset)
        {
            int delta = 0;
            foreach (var e in applied)
            {
                var ns = e.Start + delta;
                if (newOffset < ns)
                    break;
                if (newOffset < ns + e.Text.Length)
                    return e.Start;
                delta += e.Text.Length - (e.End - e.Start);
            }
            return newOffset - delta;
        }

        /// <summary>
        /// Test if a file is a generated bundle (header marker).
        /// </summary>
        public static bool IsGenerated(String text) => text.AsSpan(0, Math.Min(text.Length, 1000)).IndexOf(GeneratedMarker.AsSpan(), StringComparison.Ordinal) >= 0;

        /// <summary>
        /// Migrate a folder.
        /// </summary>
        /// <param name="root">The folder</param>
        /// <param name="options">The options (Map must be set)</param>
        /// <returns>The result</returns>
        public static MigrateResult MigrateFolder(String root, MigrateOptions options)
        {
            var map = options.Map ?? MigrationMap.Load();
            var res = new MigrateResult { DryRun = options.DryRun, Upgrade = options.KeepStyles };
            var rootFull = Path.GetFullPath(root).TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
            var skip = new PathMatcher(CheckOptions.DefaultSkip.Concat(ExtraSkip).Concat(options.Exclude));
            var include = options.Include.Count > 0 ? new PathMatcher(options.Include) : null;
            String backupFull = options.BackupDir == null ? null : Path.GetFullPath(options.BackupDir).TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
            var files = new List<FileState>();
            var byRel = new Dictionary<String, FileState>(StringComparer.OrdinalIgnoreCase);
            foreach (var w in map.LoadWarnings)
                res.Items.Add(new MigrateItem { Path = "(map)", Kind = MigrateItemKind.Warning, Message = w });

            //  A folder above the web roots (a repository): only the srcWeb / srcData folders in it (not build outputs such as web/**)
            var onlyRoots = Checker.FindWebRoots(rootFull);
            bool InRoot(String rel) => (onlyRoots == null) || onlyRoots.Any(w => rel.StartsWith(w + "/", StringComparison.OrdinalIgnoreCase) || String.Equals(rel, w, StringComparison.OrdinalIgnoreCase));
            bool AboveRoot(String rel) => onlyRoots.Any(w => w.StartsWith(rel + "/", StringComparison.OrdinalIgnoreCase));
            void Walk(String dir, String relDir)
            {
                foreach (var d in Directory.GetDirectories(dir).OrderBy(x => x, StringComparer.Ordinal))
                {
                    if ((backupFull != null) && String.Equals(Path.GetFullPath(d), backupFull, StringComparison.OrdinalIgnoreCase))
                        continue;
                    var name = Path.GetFileName(d);
                    var rel = relDir.Length == 0 ? name : (relDir + "/" + name);
                    if (skip.IsFolderMatch(rel))
                        continue;
                    if (!InRoot(rel) && !AboveRoot(rel))
                        continue;
                    Walk(d, rel);
                }
                if ((relDir.Length == 0 && (onlyRoots != null)) || ((relDir.Length > 0) && !InRoot(relDir)))
                    return;
                foreach (var f in Directory.GetFiles(dir).OrderBy(x => x, StringComparer.Ordinal))
                {
                    var name = Path.GetFileName(f);
                    var rel = relDir.Length == 0 ? name : (relDir + "/" + name);
                    var ext = Path.GetExtension(name).ToLowerInvariant();
                    if ((ext != ".js") && (ext != ".css") && (ext != ".html") && (ext != ".htm"))
                        continue;
                    if (skip.IsFileMatch(rel) || ((include != null) && !include.IsFileMatch(rel)))
                    {
                        ++res.FilesSkipped;
                        continue;
                    }
                    var src = SourceText.FromFile(f);
                    if (IsGenerated(src.Text))
                    {
                        ++res.FilesSkipped;
                        continue;
                    }
                    ++res.FilesScanned;
                    if (src.InvalidUtf8)
                    {
                        res.Items.Add(new MigrateItem { Path = rel, Kind = MigrateItemKind.Warning, Message = "not valid UTF-8: skipped" });
                        continue;
                    }
                    var fs = new FileState { Rel = rel, Full = f, Ext = ext, Src = src };
                    files.Add(fs);
                    byRel[rel] = fs;
                }
            }
            Walk(rootFull, "");

            // Pre-pass: declarations (page globals with legacy names are never renamed anywhere in the run), alias token overrides
            var runGlobals = new HashSet<String>(StringComparer.Ordinal);
            options.DefinedTokens.Clear();
            foreach (var f in files)
                TokenMigrator.FindDefinitions(f.Src.Text, map, options.DefinedTokens);
            foreach (var f in files)
            {
                if (f.Ext == ".js")
                {
                    f.Scope = new JsScope(f.Src.Text, JsLexer.Tokenize(f.Src.Text));
                    AddGlobals(f.Scope, map, runGlobals);
                }
                else if ((f.Ext == ".html") || (f.Ext == ".htm"))
                {
                    f.InlineScopes = new List<JsScope>();
                    var t = f.Src.Text;
                    foreach (var sc in HtmlScanner.GetScripts(HtmlScanner.Scan(t)))
                        if (sc.IsJavaScript && (sc.Src == null) && (sc.BodyEnd > sc.BodyStart))
                        {
                            var s = new JsScope(t, JsLexer.Tokenize(t, sc.BodyStart, sc.BodyEnd));
                            AddGlobals(s, map, runGlobals);
                        }
                }
            }

            // JavaScript files
            foreach (var f in files.Where(x => x.Ext == ".js"))
            {
                var src = f.Src;
                f.Js = JsMigrator.Analyze(f.Scope, map, options.Level, runGlobals, o => src.GetLineCol(o).Line, options.FixTranslations);
                if (options.Level >= MigrateLevel.Api)
                {
                    f.Edits.AddRange(f.Js.Edits);
                    //  Contract rule jsdoc-header: new format files start with a JSDoc file header
                    if (options.JsDocHeaders && !HasJsDocHeader(f.Scope))
                    {
                        var eol = HtmlMigrator.DetectEol(src.Text);
                        var header = "/**" + eol + " * @file " + f.Rel + " - (added by SwWeb migrate: describe the purpose of this file)." + eol + " */" + eol;
                        f.Edits.Add(new TextEdit { Start = 0, End = 0, Text = header, OldDisplay = "(no JSDoc file header)", NewDisplay = "/** @file " + f.Rel + " ... */", Note = "contract rule jsdoc-header, describe the file" });
                    }
                    //  Design token aliases in inline style strings ("color: var(--sw-muted)")
                    TokenMigrator.AnalyzeJs(src.Text, f.Scope.Sig, map, f.Edits, options.DefinedTokens);
                    if (options.Level >= MigrateLevel.Design)
                        TokenMigrator.AnalyzeLegacyJs(src.Text, f.Scope.Sig, map, f.Edits, options.DefinedTokens);
                }
                f.Items.AddRange(f.Js.Items);
            }

            // CSS files
            if (options.Level >= MigrateLevel.Api)
                foreach (var f in files.Where(x => x.Ext == ".css"))
                {
                    CssMigrator.Analyze(f.Src.Text, 0, f.Src.Text.Length, map, f.Edits, f.Items, options.KeepStyles);
                    TokenMigrator.AnalyzeCss(f.Src.Text, 0, f.Src.Text.Length, map, f.Edits, options.DefinedTokens);
                    if (options.Level >= MigrateLevel.Design)
                    {
                        TokenMigrator.AnalyzeLegacyCss(f.Src.Text, 0, f.Src.Text.Length, map, f.Edits, options.DefinedTokens);
                        DesignMigrator.AnalyzeCss(f.Src.Text, 0, f.Src.Text.Length, f.Edits);
                    }
                }

            var webRoots = files.Select(x => WebRootOf(x.Full, rootFull)).Distinct(StringComparer.OrdinalIgnoreCase).OrderBy(x => x, StringComparer.Ordinal).ToList();
            //  Which pages load which scripts (shared helper scripts: a library use only counts when no other page of the script loads it)
            //  Port steps of framework-free pages already listed (a script / style sheet shared by pages)
            var ffReported = new HashSet<(String, int)>();
            var pageIndex = new PageIndex();
            foreach (var f in files.Where(x => (x.Ext == ".html") || (x.Ext == ".htm")))
                pageIndex.Add(PageWebRel(f.Full, rootFull), f.Src.Text);
            //  The pages that load each script (true: the page has the translation functions after this run)
            var loaders = new Dictionary<FileState, List<bool>>();
            // HTML pages
            foreach (var f in files.Where(x => (x.Ext == ".html") || (x.Ext == ".htm")))
            {
                var src = f.Src;
                bool ffOnFramework = false;
                var dir = Path.GetDirectoryName(f.Full);
                PageScript Resolve(String url)
                {
                    var s = url.Trim();
                    var q = s.IndexOfAny(new[] { '?', '#' });
                    if (q >= 0)
                        s = s.Substring(0, q);
                    if ((s.Length == 0) || s.StartsWith('/') || s.Contains("://") || s.StartsWith("data:", StringComparison.OrdinalIgnoreCase) || s.StartsWith("blob:", StringComparison.OrdinalIgnoreCase))
                        return null;
                    String full;
                    try
                    {
                        full = Path.GetFullPath(Path.Combine(dir, s.Replace('/', Path.DirectorySeparatorChar)));
                    }
                    catch
                    {
                        return new PageScript { Problem = "invalid path, not analyzed" };
                    }
                    PageScript Known(String fullPath)
                    {
                        if (!fullPath.StartsWith(rootFull + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
                            return null;
                        var rel = Path.GetRelativePath(rootFull, fullPath).Replace(Path.DirectorySeparatorChar, '/');
                        if (byRel.TryGetValue(rel, out var target))
                            return new PageScript { Rel = rel, Analysis = target.Js };
                        return File.Exists(fullPath) ? new PageScript { Rel = rel } : null; // vendored, library, generated or excluded: not analyzed, not blocking
                    }
                    var k = Known(full);
                    if (k != null)
                        return k;
                    // The server merges the srcWeb folders of all projects into one web root: try the same path in the other web roots
                    var pageRoot = WebRootOf(f.Full, rootFull);
                    if (full.StartsWith(pageRoot + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
                    {
                        var inWeb = Path.GetRelativePath(pageRoot, full);
                        foreach (var wr in webRoots)
                        {
                            if (String.Equals(wr, pageRoot, StringComparison.OrdinalIgnoreCase))
                                continue;
                            k = Known(Path.Combine(wr, inWeb));
                            if (k != null)
                                return k;
                        }
                    }
                    return new PageScript { Problem = "not found in the migrated folder" + (webRoots.Count > 1 ? "s" : "") + " (served by another project?): not analyzed" };
                }
                var hr = HtmlMigrator.Migrate(src.Text, map, options, runGlobals, Resolve, o => src.GetLineCol(o).Line);
                f.Edits.AddRange(hr.Edits);
                f.Items.AddRange(hr.Items);
                if (options.Level >= MigrateLevel.Design)
                    HtmlMigrator.ReplaceCdnScripts(HtmlScanner.Scan(src.Text), PageWebRel(f.Full, rootFull), f.Edits);
                if (options.Level >= MigrateLevel.Api)
                {
                    //  Page parts: library includes of the apis the page uses, sw-root on the body (design); the scripts as they are after this run
                    var texts = new List<PageScriptText>();
                    foreach (var sc in HtmlScanner.GetScripts(HtmlScanner.Scan(src.Text)))
                    {
                        if (sc.Src == null)
                            continue;
                        var ps = Resolve(sc.Src);
                        if ((ps?.Rel != null) && byRel.TryGetValue(ps.Rel, out var st) && (st.Ext == ".js") && !Checker.IsLibraryPath(PageWebRel(st.Full, rootFull)))
                            texts.Add(new PageScriptText(PageWebRel(st.Full, rootFull), st.Edits.Count == 0 ? st.Src.Text : ApplyEdits(st.Src.Text, st.Edits).Text));
                    }
                    HtmlMigrator.AddPageParts(src.Text, hr, options, PageWebRel(f.Full, rootFull), texts, pageIndex, f.Edits, f.Items);
                }
                //  A framework-free page (rule no-framework): the includes and sw-root (--level design), its port steps as warnings at their lines
                {
                    var nodes0 = HtmlScanner.Scan(src.Text);
                    var pwr = PageWebRel(f.Full, rootFull);
                    if (!IsBelowDataRoot(f.Full, rootFull) && FrameworkFreeChecker.IsFrameworkFree(pwr, src.Text, nodes0, out var ffAnchor))
                    {
                        ++res.FrameworkFreePages;
                        bool design = options.Level >= MigrateLevel.Design;
                        var own = new List<FrameworkFreeChecker.OwnFile>();
                        var ownStates = new List<FileState>();
                        foreach (var n in nodes0)
                        {
                            if (n.Kind != HtmlNodeKind.StartTag)
                                continue;
                            bool css = (n.Name == "link") && String.Equals(n.GetAttribute("rel")?.Value?.Trim(), "stylesheet", StringComparison.OrdinalIgnoreCase);
                            var url = (n.Name == "script") ? n.GetAttribute("src") : css ? n.GetAttribute("href") : null;
                            if (url?.Value == null)
                                continue;
                            var ps = Resolve(url.Value);
                            if ((ps?.Rel == null) || !byRel.TryGetValue(ps.Rel, out var st))
                                continue;
                            var swr = PageWebRel(st.Full, rootFull);
                            if (Checker.IsLibraryPath(swr) || Checker.IsFrameworkCss(swr))
                                continue;
                            own.Add(new FrameworkFreeChecker.OwnFile(swr, st.Src.Text, css));
                            ownStates.Add(st);
                        }
                        var details = FrameworkFreeChecker.GetDetails(src.Text, nodes0, own);
                        f.Items.Add(new OffsetItem
                        {
                            Offset = ffAnchor.Start,
                            //  upgrade: the page didn't use the old framework either, so nothing changes for it (porting it is "migrate")
                            Kind = options.KeepStyles ? MigrateItemKind.Info : MigrateItemKind.Warning,
                            Message = "no-framework: " + (design
                                ? "a framework-free page: this run adds the Sw bundle includes and sw-root; the page's own code keeps working, the " + details.Count + " port step(s) are listed at their lines (PORTING.md A0)"
                                : FrameworkFreeChecker.PageMessage(details.Count) + " (run with --level design for the includes and the port steps)"),
                        });
                        if (design)
                        {
                            foreach (var d in details)
                            {
                                var target = d.File < 0 ? f : ownStates[d.File];
                                if (ffReported.Add((target.Rel, d.Offset)))
                                    target.Items.Add(new OffsetItem { Offset = d.Offset, Kind = MigrateItemKind.Warning, Message = "no-framework: port step: " + d.Message });
                            }
                            HtmlMigrator.AddFrameworkIncludes(src.Text, nodes0, pwr, f.Edits, f.Items);
                            ffOnFramework = true;
                        }
                    }
                }
                //  Which scripts this page loads, and whether the page has the translation functions after this run (design: texts get _T)
                if (options.Level >= MigrateLevel.Design)
                {
                    var scs = HtmlScanner.GetScripts(HtmlScanner.Scan(src.Text));
                    bool onFw = (ffOnFramework || scs.Any(sc => (sc.Src != null) && (Checker.IsSrc(sc.Src, "sw/core.js") || Checker.IsSrc(sc.Src, "common/common.js"))))
                        && (src.Text.IndexOf(FrameworkFreeChecker.NoFramework, StringComparison.Ordinal) < 0) && !TextChecker.IsExempt(PageWebRel(f.Full, rootFull), src.Text);
                    foreach (var sc in scs)
                    {
                        if (sc.Src != null)
                        {
                            var ps = Resolve(sc.Src);
                            if ((ps?.Rel != null) && byRel.TryGetValue(ps.Rel, out var st) && (st.Ext == ".js"))
                            {
                                if (!loaders.TryGetValue(st, out var l))
                                    loaders[st] = l = new List<bool>();
                                l.Add(onFw);
                            }
                        }
                        else if (onFw && sc.IsJavaScript && (sc.BodyEnd > sc.BodyStart))
                            WrapTexts(src.Text, JsLexer.Tokenize(src.Text, sc.BodyStart, sc.BodyEnd), f.Edits);
                    }
                }
                if (hr.IsLegacyPage)
                {
                    ++res.LegacyPages;
                    if (hr.IncludesMigrated)
                        ++res.PagesMigrated;
                    if (hr.Blocked)
                        ++res.PagesBlocked;
                    if (hr.UsesCompat)
                        ++res.PagesCompat;
                }
            }

            //  Scripts that only pages on the framework load: their user visible literal texts get _T (rule tr-untranslated)
            foreach (var kv in loaders)
                if (kv.Value.All(x => x) && !TextChecker.IsExempt(PageWebRel(kv.Key.Full, rootFull), kv.Key.Src.Text))
                    WrapTexts(kv.Key.Src.Text, JsLexer.Tokenize(kv.Key.Src.Text), kv.Key.Edits);

            // Apply (the new texts and the change report; written below)
            var changed = new List<FileState>();
            foreach (var f in files)
            {
                var src = f.Src;
                foreach (var it in f.Items)
                {
                    var (l, c) = src.GetLineCol(it.Offset);
                    res.Items.Add(new MigrateItem { Path = f.Rel, Line = l, Col = c, Kind = it.Kind, Message = it.Message });
                }
                if (f.Edits.Count == 0)
                    continue;
                f.Applied = new List<TextEdit>();
                var edits = f.Edits.OrderBy(x => x.Start).ThenBy(x => x.End).ToList();
                var sb = new StringBuilder(src.Text.Length + 256);
                int pos = 0;
                foreach (var e in edits)
                {
                    if (e.Start < pos)
                    {
                        var (l0, c0) = src.GetLineCol(e.Start);
                        res.Items.Add(new MigrateItem { Path = f.Rel, Line = l0, Col = c0, Kind = MigrateItemKind.Warning, Message = "overlapping change skipped: " + e.Text });
                        continue;
                    }
                    var old = src.Text.Substring(e.Start, e.End - e.Start);
                    if (old == e.Text)
                        continue;
                    sb.Append(src.Text, pos, e.Start - pos);
                    sb.Append(e.Text);
                    pos = e.End;
                    f.Applied.Add(e);
                    if (e.Silent)
                        continue;
                    var (l, c) = src.GetLineCol(e.ReportAt >= 0 ? e.ReportAt : e.Start);
                    res.Items.Add(new MigrateItem
                    {
                        Path = f.Rel,
                        Line = l,
                        Col = c,
                        Kind = MigrateItemKind.Change,
                        Message = OneLine(e.OldDisplay ?? old) + " -> " + OneLine(e.NewDisplay ?? e.Text) + (e.Note == null ? "" : (" (note: " + e.Note + ")")),
                    });
                }
                sb.Append(src.Text, pos, src.Text.Length - pos);
                var newText = sb.ToString();
                if (newText == src.Text)
                    continue;
                f.NewText = newText;
                res.ChangedFiles.Add(f.Rel);
                changed.Add(f);
            }

            // The porting worksheet (--level design): everything "check --strict --design" reports on the folder after this run (also in a dry
            // run: the migrated texts are checked in memory), as manual follow-ups. Lines refer to the files before this run, like the changes.
            if (options.Level >= MigrateLevel.Design)
            {
                var overlay = new Dictionary<String, String>(StringComparer.OrdinalIgnoreCase);
                foreach (var f in changed)
                    overlay[Path.GetFullPath(f.Full)] = f.NewText;
                var copt = new CheckOptions { Strict = true, Design = true, Map = map, Overlay = overlay };
                //  Lines that already have a migrate warning (the legacy names migrate couldn't rename): no second line for the same thing
                var warned = new HashSet<(String, int)>(res.Items.Where(x => x.Kind == MigrateItemKind.Warning).Select(x => (x.Path, x.Line)));
                foreach (var fd in Checker.CheckFolder(rootFull, copt).Findings)
                {
                    int line = fd.Line, col = fd.Col;
                    if (byRel.TryGetValue(fd.Path, out var fs) && (fs.Applied != null) && (fd.Line > 0))
                    {
                        var nt = new SourceText(fs.NewText);
                        var ls = nt.LineStarts;
                        var off = (fd.Line - 1 < ls.Length ? ls[fd.Line - 1] : nt.Text.Length) + Math.Max(0, fd.Col - 1);
                        (line, col) = fs.Src.GetLineCol(OldOffset(fs.Applied, Math.Min(off, nt.Text.Length)));
                    }
                    if (((fd.Rule == Rule.LegacyGlobal) || (fd.Rule == Rule.LegacyCompat) || (fd.Rule == Rule.DesignConfirm)) && warned.Contains((fd.Path, line)))
                        continue;
                    res.Items.Add(new MigrateItem { Path = fd.Path, Line = line, Col = col, Kind = MigrateItemKind.Warning, Message = (fd.Rule.Design ? "design: " : "check: ") + fd.Rule.Id + ": " + fd.Message });
                }
            }

            // Write
            if (!options.DryRun)
                foreach (var f in changed)
                {
                    if (backupFull != null)
                    {
                        var b = Path.Combine(backupFull, f.Rel.Replace('/', Path.DirectorySeparatorChar));
                        Directory.CreateDirectory(Path.GetDirectoryName(b));
                        File.Copy(f.Full, b, true);
                    }
                    var bytes = new UTF8Encoding(false).GetBytes(f.NewText);
                    if (f.Src.HadBom)
                        bytes = new byte[] { 0xef, 0xbb, 0xbf }.Concat(bytes).ToArray();
                    File.WriteAllBytes(f.Full, bytes);
                }
            res.Items.Sort((a, b) =>
            {
                var x = String.CompareOrdinal(a.Path, b.Path);
                if (x != 0)
                    return x;
                x = a.Line.CompareTo(b.Line);
                return x != 0 ? x : a.Col.CompareTo(b.Col);
            });
            return res;
        }

        /// <summary>
        /// The web root of a file: the nearest parent folder named "srcWeb" or "srcData" (inside the migrated folder), else the migrated folder.
        /// </summary>
        /// <summary>
        /// True if a file is in a srcData folder (server side templates and data: no UI pages).
        /// </summary>
        static bool IsBelowDataRoot(String file, String rootFull)
        {
            for (var d = new DirectoryInfo(Path.GetDirectoryName(file)); d != null; d = d.Parent)
            {
                if (String.Equals(d.Name, "srcData", StringComparison.OrdinalIgnoreCase))
                    return true;
                if (String.Equals(d.Name, "srcWeb", StringComparison.OrdinalIgnoreCase))
                    return false;
            }
            return false;
        }

        static String WebRootOf(String file, String rootFull)
        {
            var d = Path.GetDirectoryName(file);
            while ((d != null) && (d.Length > rootFull.Length))
            {
                var n = Path.GetFileName(d);
                if (String.Equals(n, "srcWeb", StringComparison.OrdinalIgnoreCase) || String.Equals(n, "srcData", StringComparison.OrdinalIgnoreCase))
                    return d;
                d = Path.GetDirectoryName(d);
            }
            return rootFull;
        }

        /// <summary>
        /// The path of a file relative to its web root (srcWeb / srcData), also when the migrated folder is a sub folder of a web root.
        /// </summary>
        static String PageWebRel(String file, String rootFull)
        {
            var wr = WebRootOf(file, rootFull);
            var rel = Path.GetRelativePath(wr, file).Replace(Path.DirectorySeparatorChar, '/');
            return String.Equals(wr, rootFull, StringComparison.OrdinalIgnoreCase) ? (Checker.GetWebPrefix(rootFull) + rel) : rel;
        }

        /// <summary>
        /// Wrap the user visible literal texts of a script that migrate can wrap as they are (TextChecker.FindTexts, Wrappable) in _T(...):
        /// "Sw.Toast("Saved")" becomes "Sw.Toast(_T("Saved"))" (rule tr-untranslated). Not: a literal on a line marked SwWeb:no-tr, a literal
        /// that another edit of the run touches.
        /// </summary>
        static void WrapTexts(String text, List<JsToken> tokens, List<TextEdit> edits)
        {
            var src = new SourceText(text);
            foreach (var s in TextChecker.FindTexts(text, tokens))
            {
                if (!s.Wrappable || edits.Any(e => (e.Start < s.End) && (e.End > s.Start)))
                    continue;
                var (l, _) = src.GetLineCol(s.Start);
                var ls = src.LineStarts;
                var from = ls[Math.Max(0, l - 2)];
                var to = l < ls.Length ? ls[l] : text.Length;
                if (text.IndexOf(TextChecker.NoTr, from, to - from, StringComparison.Ordinal) >= 0)
                    continue;
                var raw = text.Substring(s.Start, s.End - s.Start);
                edits.Add(new TextEdit
                {
                    Start = s.Start, End = s.End, Text = "_T(" + raw + ")", OldDisplay = raw, NewDisplay = "_T(" + raw + ")",
                    Note = "rule tr-untranslated: " + s.Where + " is shown to people; add a context for the translators: _T(" + raw + ", \"where it is shown\")",
                });
            }
        }

        static void AddGlobals(JsScope s, MigrationMap map, HashSet<String> runGlobals)
        {
            foreach (var n in s.TopLevel)
                if (map.IsLegacy(n) || map.IsShell(n))
                    runGlobals.Add(n);
        }

        static String OneLine(String s)
        {
            s = s.Replace("\r\n", "⏎").Replace('\n', '⏎').Replace('\r', '⏎');
            return s.Length > 200 ? (s.Substring(0, 197) + "...") : s;
        }

        /// <summary>
        /// Write the report: markdown if the file name ends with ".md", else plain text.
        /// </summary>
        /// <param name="res">The result</param>
        /// <param name="root">The migrated folder (shown in the header)</param>
        /// <param name="fileName">The report file</param>
        public static void WriteReport(MigrateResult res, String root, String fileName)
        {
            var md = fileName.EndsWith(".md", StringComparison.OrdinalIgnoreCase);
            File.WriteAllText(fileName, FormatReport(res, root, md), new UTF8Encoding(false));
        }

        /// <summary>
        /// Test if JavaScript code starts with a JSDoc file header (the first comment / token is a "/** ... @file ... */" block comment).
        /// </summary>
        /// <param name="scope">The code</param>
        /// <returns>True if it has one (or the file is empty)</returns>
        static bool HasJsDocHeader(JsScope scope)
        {
            var tokens = JsLexer.Tokenize(scope.Text);
            foreach (var t in tokens)
            {
                if (t.Kind == JsTokenKind.Whitespace)
                    continue;
                if (t.Kind == JsTokenKind.BlockComment)
                {
                    var txt = t.GetText(scope.Text);
                    return txt.StartsWith("/**", StringComparison.Ordinal) && txt.Contains("@file", StringComparison.Ordinal);
                }
                return false;
            }
            return true;
        }

        /// <summary>
        /// Format the report.
        /// </summary>
        public static String FormatReport(MigrateResult res, String root, bool markdown)
        {
            var sb = new StringBuilder();
            var nl = "\n";
            String Esc(String s) => markdown ? s.Replace("|", "\\|").Replace("<", "&lt;") : s;
            if (markdown)
            {
                sb.Append(res.Upgrade ? "# SwWeb upgrade report" : "# SwWeb migrate report").Append(nl).Append(nl);
                sb.Append("Folder: `").Append(root).Append("`").Append(res.DryRun ? " (dry run, nothing written)" : "").Append(nl).Append(nl);
                sb.Append("| | |").Append(nl).Append("|---|---|").Append(nl);
                sb.Append("| Files analyzed | ").Append(res.FilesScanned).Append(" (").Append(res.FilesSkipped).Append(" skipped) |").Append(nl);
                sb.Append("| Files changed | ").Append(res.ChangedFiles.Count).Append(" |").Append(nl);
                sb.Append("| Changes | ").Append(res.Changes).Append(" |").Append(nl);
                sb.Append("| Legacy pages | ").Append(res.LegacyPages).Append(" (").Append(res.PagesMigrated).Append(" migrated, ").Append(res.PagesCompat).Append(" of them with sw/compat.js, ").Append(res.PagesBlocked).Append(" kept on the legacy bundles) |").Append(nl);
                sb.Append("| Framework-free pages | ").Append(res.FrameworkFreePages).Append(" (no Sw or legacy bundle: rule no-framework, PORTING.md A0) |").Append(nl);
                sb.Append("| Warnings (manual follow-up) | ").Append(res.Warnings).Append(" |").Append(nl);
                sb.Append("| Info | ").Append(res.Infos).Append(" |").Append(nl).Append(nl);
                //  The manual work by rule (the "check:" / "design:" items are what check --strict --design reports after this run)
                var byRule = res.Items.Where(x => x.Kind == MigrateItemKind.Warning)
                    .Select(x => System.Text.RegularExpressions.Regex.Match(x.Message, @"^(?:check|design): (?<r>[a-z0-9-]+):|^(?<r>no-framework):"))
                    .Select(m => m.Success ? m.Groups["r"].Value : "migrate (API names, includes)")
                    .GroupBy(x => x).OrderByDescending(g => g.Count()).ThenBy(g => g.Key, StringComparer.Ordinal).ToList();
                if (byRule.Count > 0)
                {
                    sb.Append("Manual follow-ups by rule (PORTING.md has a section per rule; lines refer to the files before this run):").Append(nl).Append(nl);
                    sb.Append("| Rule | Warnings |").Append(nl).Append("|---|---|").Append(nl);
                    foreach (var g in byRule)
                        sb.Append("| ").Append(g.Key).Append(" | ").Append(g.Count()).Append(" |").Append(nl);
                    sb.Append(nl);
                }
                foreach (var kind in new[] { MigrateItemKind.Change, MigrateItemKind.Warning, MigrateItemKind.Info })
                {
                    var items = res.Items.Where(x => x.Kind == kind).ToList();
                    sb.Append("## ").Append(kind == MigrateItemKind.Change ? "Changes" : kind == MigrateItemKind.Warning ? "Warnings (manual follow-up)" : "Info").Append(" (").Append(items.Count).Append(")").Append(nl).Append(nl);
                    foreach (var g in items.GroupBy(x => x.Path))
                    {
                        sb.Append("### ").Append(g.Key).Append(nl).Append(nl);
                        foreach (var it in g)
                            sb.Append("- ").Append(it.Line > 0 ? ("L" + it.Line + ": ") : "").Append(Esc(it.Message)).Append(nl);
                        sb.Append(nl);
                    }
                }
            }
            else
            {
                sb.Append(res.Upgrade ? "SwWeb upgrade report: " : "SwWeb migrate report: ").Append(root).Append(res.DryRun ? " (dry run, nothing written)" : "").Append(nl);
                sb.Append(Summary(res)).Append(nl).Append(nl);
                foreach (var it in res.Items)
                    sb.Append(it.Format()).Append(nl);
            }
            return sb.ToString();
        }

        /// <summary>
        /// A one line summary.
        /// </summary>
        public static String Summary(MigrateResult res) =>
            res.FilesScanned + " file(s) analyzed, " + res.FilesSkipped + " skipped; " + res.ChangedFiles.Count + " file(s) " + (res.DryRun ? "would change" : "changed")
            + ", " + res.Changes + " change(s); legacy pages: " + res.LegacyPages + " (" + res.PagesMigrated + " migrated, " + res.PagesCompat + " of them with sw/compat.js, " + res.PagesBlocked + " kept on the legacy bundles); framework-free pages: " + res.FrameworkFreePages + "; "
            + res.Warnings + " warning(s), " + res.Infos + " info(s)";
    }
