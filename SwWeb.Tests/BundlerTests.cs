        const String Manifest = "{ \"Bundles\": [ { \"Out\": \"sw/core.js\", \"Header\": \"Core bundle\", \"Files\": [\"core/b.js\", \"core/a.js\"] }, { \"Out\": \"sw/ui.css\", \"Files\": [\"ui/x.css\", \"ui/y.css\"] } ] }";

        static TestFolder Setup()
        {
            var f = new TestFolder();
            f.Write("sw/bundles.json", Manifest);
            f.Write("core/a.js", "/** @file a */\nvar A = 1\n", true);
            f.Write("core/b.js", "\n\n/** @file b */\r\nfunction B() {\r\n}\r\n", true);
            f.Write("ui/x.css", "/* x */\n.x { color: red; }", true);
            f.Write("ui/y.css", ".y { color: blue; }\n", false);
            return f;
        }

        static List<BundleResult> Build(TestFolder f, bool check) =>
            Bundler.BuildAll(f.Root, BundleManifest.Load(f.PathOf("sw/bundles.json")), "sw/bundles.json", check);

        [Fact]
        public void BuildsInManifestOrderWithHeaderAndSeparators()
        {
            using var f = Setup();
            var r = Build(f, false);
            Assert.All(r, x => Assert.Equal(BundleStatus.Written, x.Status));
            var bytes = f.ReadBytes("sw/core.js");
            Assert.Equal(new byte[] { 0xef, 0xbb, 0xbf }, bytes.Take(3).ToArray());
            var text = f.Read("sw/core.js");
            Assert.DoesNotContain('﻿', text);
            Assert.StartsWith("/**\r\n * @file sw/core.js: GENERATED by SwWeb bundle from sw/bundles.json, do not edit!", text);
            Assert.Contains(" * Core bundle\r\n", text);
            Assert.Contains(" * Sources (in order):\r\n *   core/b.js\r\n *   core/a.js\r\n */", text);
            var ib = text.IndexOf("// ---- core/b.js ----\r\n/** @file b */", StringComparison.Ordinal);
            var ia = text.IndexOf("// ---- core/a.js ----\r\n/** @file a */", StringComparison.Ordinal);
            Assert.True(ib > 0);
            Assert.True(ia > ib);
            // Only CRLF line endings
            Assert.Equal(text.Count(c => c == '\n'), text.Split("\r\n").Length - 1);
            Assert.DoesNotContain("\r\r", text);
            // a.js doesn't end with ';' so one is added, b.js ends with '}' followed by "var" so none is needed
            Assert.EndsWith("var A = 1\r\n;\r\n", text);
            Assert.Contains("function B() {\r\n}\r\n\r\n// ---- core/a.js", text);
            var css = f.Read("sw/ui.css");
            Assert.Contains("/* ---- ui/x.css ---- */\r\n/* x */\r\n.x { color: red; }\r\n\r\n/* ---- ui/y.css ---- */\r\n.y { color: blue; }\r\n", css);
        }

        [Fact]
        public void CheckModeDetectsOutOfDateAndDoesNotWrite()
        {
            using var f = Setup();
            Assert.All(Build(f, true), x => Assert.Equal(BundleStatus.OutOfDate, x.Status));
            Assert.False(File.Exists(f.PathOf("sw/core.js")));
            Build(f, false);
            Assert.All(Build(f, true), x => Assert.Equal(BundleStatus.UpToDate, x.Status));
            Assert.All(Build(f, false), x => Assert.Equal(BundleStatus.UpToDate, x.Status));
            var before = f.ReadBytes("sw/core.js");
            f.Write("core/a.js", "/** @file a */\nvar A = 2;\n");
            var r = Build(f, true);
            Assert.Equal(BundleStatus.OutOfDate, r[0].Status);
            Assert.Equal(BundleStatus.UpToDate, r[1].Status);
            Assert.Equal(before, f.ReadBytes("sw/core.js"));
            Assert.Equal(BundleStatus.Written, Build(f, false)[0].Status);
        }

        [Fact]
        public void LineEndingsAndBomOfSourcesDontMatter()
        {
            var a = Bundler.Concatenate("x.js", new[] { new BundleSource("a.js", "﻿/** @file a */\nvar a = 1;\n") }, null, "m.json");
            var b = Bundler.Concatenate("x.js", new[] { new BundleSource("a.js", "/** @file a */\r\nvar a = 1;\r\n\r\n") }, null, "m.json");
            var c = Bundler.Concatenate("x.js", new[] { new BundleSource("a.js", "/** @file a */\rvar a = 1;") }, null, "m.json");
            Assert.Equal(a, b);
            Assert.Equal(a, c);
        }

        [Theory]
        [InlineData("var a = 1", "var b;", true)]
        [InlineData("var a = 1;", "(function(){})();", false)]
        [InlineData("function f() {}", "var b;", false)]
        [InlineData("var o = {}", "(function(){})();", true)]
        [InlineData("function f() {}", "[1].forEach(f);", true)]
        [InlineData("function f() {}", "`x`.length;", true)]
        [InlineData("var a = 1 // comment", "var b;", true)]
        public void SemicolonSeparation(String first, String second, bool semi)
        {
            var t = Bundler.Concatenate("x.js", new[] { new BundleSource("a.js", first), new BundleSource("b.js", second) }, null, "m.json");
            var i = t.IndexOf("// ---- b.js", StringComparison.Ordinal);
            var between = t.Substring(0, i);
            Assert.Equal(semi, between.EndsWith("\r\n;\r\n\r\n", StringComparison.Ordinal));
        }

        [Fact]
        public void UnterminatedCommentIsAnError()
        {
            var errors = new List<String>();
            Bundler.Concatenate("x.js", new[] { new BundleSource("a.js", "var a; /* oops"), new BundleSource("b.js", "var b;") }, null, "m.json", errors);
            Assert.Single(errors);
            Assert.StartsWith("a.js: unterminated block comment", errors[0]);
            errors.Clear();
            Bundler.Concatenate("x.css", new[] { new BundleSource("a.css", ".a{} /* oops") }, null, "m.json", errors);
            Assert.Single(errors);
        }

        [Fact]
        public void HeaderCantCloseTheComment()
        {
            var t = Bundler.Concatenate("x.js", new[] { new BundleSource("a.js", "var a;") }, "evil */ alert(1)", "m.json");
            Assert.DoesNotContain("evil */", t);
            Assert.Contains("evil * / alert(1)", t);
        }

        [Fact]
        public void MissingFilesAreReported()
        {
            using var f = Setup();
            File.Delete(f.PathOf("core/a.js"));
            var r = Build(f, false);
            Assert.Equal(BundleStatus.Failed, r[0].Status);
            Assert.Equal(new[] { "core/a.js" }, r[0].MissingFiles);
