        [Fact]
        public void InvalidDefinitions()
        {
            using var f = Setup();
            f.Write("sw/bad.json", "{ \"Bundles\": [ { \"Out\": \"sw/a.b.js\", \"Files\": [\"core/a.js\"] }, { \"Out\": \"sw/c.js\", \"Files\": [\"../x.js\", \"ui/x.css\", \"core/a.js\", \"core/a.js\"] }, { \"Out\": \"sw/c.js\", \"Files\": [\"core/a.js\"] }, ] }");
            var r = Bundler.BuildAll(f.Root, BundleManifest.Load(f.PathOf("sw/bad.json")), "sw/bad.json", false);
            Assert.All(r, x => Assert.Equal(BundleStatus.Failed, x.Status));
            Assert.Contains(r[0].Errors, e => e.Contains("single dot"));
            Assert.Contains(r[1].Errors, e => e.Contains("used by more than one bundle"));
            var single = Bundler.Build(f.Root, new BundleDefinition { Out = "sw/c.js", Files = { "../x.js", "ui/x.css", "core/a.js", "core/a.js" } }, "m", false);
            Assert.Contains(single.Errors, e => e.StartsWith("../x.js") && e.Contains("inside the web root"));
            Assert.Contains(single.Errors, e => e.StartsWith("ui/x.css") && e.Contains("same extension"));
            Assert.Contains(single.Errors, e => e.StartsWith("core/a.js") && e.Contains("more than once"));
        }

        [Fact]
        public void CommandLineExitCodes()
        {
            using var f = Setup();
            Assert.Equal(SwWebProgram.ExitProblems, SwWebProgram.Run(new[] { "bundle", f.Root, "--check" }));
            Assert.Equal(SwWebProgram.ExitSuccess, SwWebProgram.Run(new[] { "bundle", f.Root }));
            Assert.Equal(SwWebProgram.ExitSuccess, SwWebProgram.Run(new[] { "bundle", f.Root, "--check" }));
            File.Copy(f.PathOf("sw/bundles.json"), f.PathOf("other.json"));
            // Another manifest name changes the generated header, so the bundles are out of date for it
            Assert.Equal(SwWebProgram.ExitProblems, SwWebProgram.Run(new[] { "bundle", f.Root, "--check", "--manifest", f.PathOf("other.json") }));
            File.Delete(f.PathOf("ui/y.css"));
            Assert.Equal(SwWebProgram.ExitMissingFiles, SwWebProgram.Run(new[] { "bundle", f.Root, "--check" }));
            Assert.Equal(SwWebProgram.ExitInvalidArguments, SwWebProgram.Run(new[] { "bundle", f.Root, "--bogus" }));
            Assert.Equal(SwWebProgram.ExitInvalidArguments, SwWebProgram.Run(new[] { "bundle", f.PathOf("nope") }));
            Assert.Equal(SwWebProgram.ExitInvalidArguments, SwWebProgram.Run(new String[0]));
            Assert.Equal(SwWebProgram.ExitSuccess, SwWebProgram.Run(new[] { "-?" }));
        }

        [Fact]
        public void LoadOnceWrapsEverySourceInAGuard()
        {
            using var f = new TestFolder();
            f.Write("core/a.js", "/** @file a */\n(function () {\n    \"use strict\";\n    window.A = 1;\n})()\n", true);
            f.Write("core/b.js", "(() => {\n    window.B = 2;\n})();\n", false);
            var r = Bundler.Build(f.Root, new BundleDefinition { Out = "sw/session.js", LoadOnce = true, Files = { "core/a.js", "core/b.js" } }, "sw/bundles.json", false);
            Assert.Equal(BundleStatus.Written, r.Status);
            var text = f.Read("sw/session.js");
            Assert.Contains(" * Load once: each source runs once per page", text);
            // a.js: guard, the source, a ';' (its last token is ')'), the block end
            Assert.Contains("// ---- core/a.js ----\r\nif (!((window.Sw = window.Sw || {}).Sources = window.Sw.Sources || {})[\"core/a.js\"]) {\r\nwindow.Sw.Sources[\"core/a.js\"] = \"sw/session.js\";\r\n/** @file a */\r\n(function () {", text);
            Assert.Contains("})()\r\n;\r\n}\r\n\r\n// ---- core/b.js ----\r\nif (!((window.Sw = window.Sw || {}).Sources = window.Sw.Sources || {})[\"core/b.js\"]) {\r\nwindow.Sw.Sources[\"core/b.js\"] = \"sw/session.js\";\r\n(() => {", text);
            Assert.EndsWith("})();\r\n}\r\n", text);
            // the same sources without LoadOnce: no guard
            var plain = Bundler.Build(f.Root, new BundleDefinition { Out = "sw/core.js", Files = { "core/a.js", "core/b.js" } }, "sw/bundles.json", false);
            Assert.Equal(BundleStatus.Written, plain.Status);
            Assert.DoesNotContain("Sw.Sources", f.Read("sw/core.js"));
            // the manifest member
            Assert.True(BundleManifest.Parse("{ \"Bundles\": [ { \"Out\": \"sw/x.js\", \"LoadOnce\": true, \"Files\": [\"a.js\"] } ] }").Bundles[0].LoadOnce);
            Assert.False(BundleManifest.Parse("{ \"Bundles\": [ { \"Out\": \"sw/x.js\", \"Files\": [\"a.js\"] } ] }").Bundles[0].LoadOnce);
        }

        [Fact]
        public void LoadOnceRefusesTopLevelDeclarations()
        {
            using var f = new TestFolder();
            f.Write("core/a.js", "const A = 1;\nlet b = 2;\nclass C {}\nfunction d() {}\nasync function e() {}\nfunction* g() {}\n", false);
            f.Write("core/ok.js", "(function () { const x = 1; function y() {} })();\n!function () { let z; }();\nvar v = 1;\nif (v) { const w = 2; }\nwindow.f = function f() {};\n", false);
            f.Write("ui/x.css", ".x{}", false);
            var r = Bundler.Build(f.Root, new BundleDefinition { Out = "sw/x.js", LoadOnce = true, Files = { "core/a.js", "core/ok.js" } }, "m", false);
            Assert.Equal(BundleStatus.Failed, r.Status);
            Assert.False(File.Exists(f.PathOf("sw/x.js")));
            foreach (var d in new[] { "const A", "let b", "class C", "function d", "function e", "function g" })
                Assert.Contains(r.Errors, e => e.StartsWith("core/a.js: top level declaration \"" + d + "\"", StringComparison.Ordinal));
            Assert.DoesNotContain(r.Errors, e => e.StartsWith("core/ok.js", StringComparison.Ordinal));
            Assert.Empty(Bundler.TopLevelDeclarations(f.Read("core/ok.js")));
            // without LoadOnce the same sources are fine
            Assert.Equal(BundleStatus.Written, Bundler.Build(f.Root, new BundleDefinition { Out = "sw/y.js", Files = { "core/a.js", "core/ok.js" } }, "m", false).Status);
            // a source that only declares global functions (core/i18n.js: the translation markers) is not wrapped: they stay plain global functions
            f.Write("core/i18n.js", "function _T(format) {\n    return format;\n}\n(function () {\n    if (window.Sw && window.Sw.I18n)\n        return;\n})();\n", false);
            var fr = Bundler.Build(f.Root, new BundleDefinition { Out = "sw/z.js", LoadOnce = true, Files = { "core/i18n.js", "core/ok.js" } }, "m", false);
            Assert.Equal(BundleStatus.Written, fr.Status);
            var z = f.Read("sw/z.js");
            Assert.Contains("// ---- core/i18n.js ----\r\n// (not guarded: it declares global functions, its other code runs once by itself)\r\nfunction _T(format) {", z);
            Assert.DoesNotContain("[\"core/i18n.js\"]", z);
            Assert.Contains("[\"core/ok.js\"]", z);
            // a css bundle can't be load once
            var css = Bundler.Build(f.Root, new BundleDefinition { Out = "sw/x.css", LoadOnce = true, Files = { "ui/x.css" } }, "m", false);
            Assert.Contains(css.Errors, e => e.Contains("only valid for a .js bundle"));
        }

        [Fact]
        public void ABundleThatSharesASourceWithALoadOnceBundleMustBeLoadOnce()
        {
            //  AS6-1: common/common.js (LoadOnce) and sw/ui.js (not) both contain ui/base.js: a page with both ran the ui twice
            using var f = new TestFolder();
            f.Write("core/k.js", "(function () { window.K = 1; })();\n", false);
            f.Write("ui/base.js", "(function () { window.U = 1; })();\n", false);
            var m = BundleManifest.Parse("{ \"Bundles\": [ { \"Out\": \"common/common.js\", \"LoadOnce\": true, \"Files\": [\"core/k.js\", \"ui/base.js\"] }, { \"Out\": \"sw/ui.js\", \"Files\": [\"ui/base.js\"] } ] }");
            var res = Bundler.BuildAll(f.Root, m, "sw/bundles.json", false);
            Assert.Equal(BundleStatus.Written, res[0].Status);
            Assert.Equal(BundleStatus.Failed, res[1].Status);
            Assert.Contains(res[1].Errors, e => e.Contains("ui/base.js is also in common/common.js (LoadOnce)", StringComparison.Ordinal));
            Assert.Contains(m.Bundles[1].Out, Bundler.LoadOnceConflicts(m).Keys);
            //  Both LoadOnce: fine
            m.Bundles[1].LoadOnce = true;
            Assert.Empty(Bundler.LoadOnceConflicts(m));
            Assert.All(Bundler.BuildAll(f.Root, m, "sw/bundles.json", false), r => Assert.NotEqual(BundleStatus.Failed, r.Status));
        }

        [Fact]
        public void SizeBudgetIsReportedAndChecked()
        {
            //  AS6-6: a bundle over its MaxKB / MaxGzipKB fails build and check (it is still generated), the sizes are reported
            using var f = new TestFolder();
            f.Write("core/a.js", "(function () { window.A = \"" + new String('x', 3000) + "\"; })();\n", false);
            var ok = Bundler.Build(f.Root, new BundleDefinition { Out = "sw/a.js", LoadOnce = true, MaxKB = 10, MaxGzipKB = 2, Files = { "core/a.js" } }, "m", false);
            Assert.Equal(BundleStatus.Written, ok.Status);
            Assert.Empty(ok.OverBudget);
            Assert.True(ok.Size > 3000);
            Assert.True((ok.GzipSize > 0) && (ok.GzipSize < ok.Size));
            var over = Bundler.Build(f.Root, new BundleDefinition { Out = "sw/a.js", LoadOnce = true, MaxKB = 1, MaxGzipKB = 0.01, Files = { "core/a.js" } }, "m", true);
            Assert.Equal(BundleStatus.UpToDate, over.Status);
            Assert.Equal(2, over.OverBudget.Count);
            Assert.Contains(over.OverBudget, e => e.Contains("over its budget \"MaxKB\": 1", StringComparison.Ordinal));
            Assert.Contains(over.OverBudget, e => e.Contains("gzip is over its budget \"MaxGzipKB\"", StringComparison.Ordinal));
            Assert.Equal(1.5, BundleManifest.Parse("{ \"Bundles\": [ { \"Out\": \"sw/x.js\", \"MaxKB\": 1.5, \"Files\": [\"a.js\"] } ] }").Bundles[0].MaxKB);
        }

        [Fact]
        public void TheBuiltInBundleListIsTheFrameworkManifest()
        {
            //  The copy SwWeb check uses (rule bundle-overlap) when the checked folder has no sw/bundles.json: equal to SysWeaver's
            var repo = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "..", "..", "..", "..", "..", "SysWeaver", "SysWeaver.HttpServer", "srcWeb", "sw", "bundles.json"));
            var builtIn = SwWeb.Checking.PageChecker.BuiltInBundles;
            Assert.Contains(builtIn.Bundles, b => b.Out == "common/common.js" && b.LoadOnce);
            Assert.All(builtIn.Bundles.Where(b => b.Out.EndsWith(".js", StringComparison.Ordinal)), b => Assert.True(b.LoadOnce, b.Out));
            if (!File.Exists(repo))
                return;
            String Key(BundleManifest m) => String.Join("\n", m.Bundles.Select(b => b.Out + " " + b.LoadOnce + " " + String.Join(",", b.Files)));
            Assert.Equal(Key(BundleManifest.Load(repo)), Key(builtIn));
        }
